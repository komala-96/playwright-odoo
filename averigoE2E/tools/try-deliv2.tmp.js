const { chromium } = require('@playwright/test');
const env = require('../config/env');
const { SalesPage } = require('../pages/SalesPage');
(async () => {
  const so = process.argv[2] || 'S01312';
  const b = await chromium.launch();
  const c = await b.newContext({ storageState: env.AUTH_FILE, baseURL: env.BASE_URL, viewport: { width: 1600, height: 1000 } });
  const p = await c.newPage();
  await p.addLocatorHandler(p.locator('.modal.o_technical_modal').filter({ hasText: 'Open Customer Activities' }), (m) => m.locator('.btn-close').first().click({ timeout: 5000 }).catch(() => m.page().keyboard.press('Escape')));
  const o = new SalesPage(p);
  await o.openApp('Customer Care'); await o.openMenu('Delivery', 'Packing Slip');
  console.log('URL', p.url());
  console.log('COLS', await p.locator('.o_list_view th[data-name]').evaluateAll((t) => t.map((x) => x.dataset.name + ':' + x.innerText.trim()).join(' | ')));
  console.log('ROWS', (await o.rows().allInnerTexts()).slice(0, 4));
  const row = o.rows().first();
  await row.locator('td.o_data_cell').first().click(); await o.waitReady(); await p.waitForTimeout(1500);
  console.log('FORM URL', p.url());
  console.log('FIELDS', await p.evaluate(() => [...document.querySelectorAll('.o_form_view .o_field_widget[name]')].filter((e) => e.offsetParent && !e.closest('.o_data_row')).map((e) => e.getAttribute('name')).join(' ')));
  console.log('LINE COLS', await p.locator('.o_form_view th[data-name]').evaluateAll((t) => t.map((x) => x.dataset.name + ':' + x.innerText.trim()).join(' | ')));
  console.log('LINES', await p.locator('.o_form_view .o_data_row').allInnerTexts());
  console.log('BUTTONS', await p.evaluate(() => [...document.querySelectorAll('.o_form_view button')].filter((b) => b.offsetParent && b.innerText.trim()).map((b) => b.innerText.trim().replace(/\s+/g, ' ') + (b.name ? `{${b.name}}` : '')).join(' | ')));
  await o.fill({ select_all_delivery: true }); await p.waitForTimeout(800);
  await o.click('deliver_pack_slip_wizard'); await p.waitForTimeout(2000);
  const m = p.locator('.modal:visible').last();
  console.log('WIZARD', (await m.innerText().catch(() => 'none')).replace(/\s+/g, ' ').slice(0, 600));
  console.log('WIZ FIELDS', await m.evaluate((e) => [...e.querySelectorAll('.o_field_widget[name]')].filter((x) => x.offsetParent).map((x) => x.getAttribute('name')).join(' ')).catch(() => ''));
  console.log('WIZ BUTTONS', await m.evaluate((e) => [...e.querySelectorAll('button')].filter((b) => b.offsetParent && b.innerText.trim()).map((b) => b.innerText.trim() + (b.name ? `{${b.name}}` : '')).join(' | ')).catch(() => ''));
  await m.locator('button[name=action_confirm_delivery]').click(); await o.waitReady(); await p.waitForTimeout(2500);
  console.log('AFTER MODALS', (await p.locator('.modal:visible').allInnerTexts()).map((t) => t.slice(0, 300)));
  console.log('LINES AFTER', await p.locator('.o_form_view .o_data_row').allInnerTexts());
  await o.openMenu('Orders'); await o.search(so); await o.rows(so).first().locator('td.o_data_cell').first().click(); await o.waitReady();
  console.log('ORDER STATUS', (await p.locator('.o_statusbar_status').innerText()).replace(/\s+/g, ' '));
  console.log('ORDER BUTTONS', await p.evaluate(() => [...document.querySelectorAll('.o_form_view button')].filter((b) => b.offsetParent && b.innerText.trim()).map((b) => b.innerText.trim().replace(/\s+/g, ' ') + (b.name ? `{${b.name}}` : '')).join(' | ')));
  await b.close();
})();
