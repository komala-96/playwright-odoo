const { chromium } = require('@playwright/test');
const env = require('../config/env');
const { ReportsPage } = require('../pages/ReportsPage');
const { today } = require('../utils/dates');
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ storageState: env.AUTH_FILE, baseURL: env.BASE_URL, viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
  const p = await c.newPage();
  await p.addLocatorHandler(p.locator('.modal.o_technical_modal').filter({ hasText: 'Open Customer Activities' }), (m) => m.locator('.btn-close').first().click({ timeout: 5000 }).catch(() => m.page().keyboard.press('Escape')));
  p.on('download', (dl) => console.log('DOWNLOAD', dl.suggestedFilename()));
  p.on('popup', (pp) => console.log('POPUP', pp.url()));
  const r = new ReportsPage(p);
  await r.openReport('Accounts Receivable', 'Invoice Export Report');
  await r.setFilters({ start: today(), end: today() });
  await r.generate();
  console.log('ROWS', (await r.output()).split('\n').slice(0, 3));
  console.log('BUTTONS', await p.locator('.o_action_manager button').filter({ visible: true }).allInnerTexts());
  await p.locator('.o_action_manager button').filter({ hasText: /Export/ }).first().click(); await p.waitForTimeout(4000);
  console.log('AFTER EXPORT modals', (await p.locator('.modal:visible, .dropdown-menu.show').allInnerTexts()).map((t) => t.slice(0, 200)));
  await p.screenshot({ path: 'tools/last.png' });
  await b.close();
})();
