const { chromium } = require('@playwright/test');
const env = require('../config/env');
const state = require('../utils/state');
const { CustomerCarePage } = require('../pages/CustomerCarePage');
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ storageState: env.AUTH_FILE, baseURL: env.BASE_URL, viewport: { width: 1600, height: 1000 } });
  const p = await c.newPage();
  await p.addLocatorHandler(p.locator('.modal.o_technical_modal').filter({ hasText: 'Open Customer Activities' }), (m) => m.locator('.btn-close').first().click({ timeout: 5000 }).catch(() => m.page().keyboard.press('Escape')));
  const i = new CustomerCarePage(p);
  await i.goto(state.get('customer1Url'));
  console.log('po_no visible:', await i.field('po_no').isVisible().catch(() => false), 'value:', await i.read('po_no').catch(() => '?'));
  await i.openTab('Order Products');
  const pane = p.locator('.o_form_view .o_notebook .tab-pane.active');
  console.log('PANE TEXT:', (await pane.innerText()).slice(0, 1200).replace(/\n+/g, ' | '));
  console.log('PANE FIELDS:', await pane.evaluate((el) => [...el.querySelectorAll('.o_field_widget[name]')].filter((e) => e.offsetParent).map((e) => e.getAttribute('name')).join(' ')));
  console.log('PANE BUTTONS:', (await pane.locator('button').filter({ visible: true }).evaluateAll((bs) => bs.map((x) => `${x.innerText.trim()}{${x.getAttribute('name') || ''}}`))).join(' | '));
  await p.screenshot({ path: 'tools/last.png', fullPage: true });
  await b.close();
})();
