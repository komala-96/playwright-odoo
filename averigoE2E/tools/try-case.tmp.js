const { chromium } = require('@playwright/test');
const env = require('../config/env');
const d = require('../data/testData');
const { ServicePage } = require('../pages/OtherModulesPage');
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ storageState: env.AUTH_FILE, baseURL: env.BASE_URL, viewport: { width: 1600, height: 1000 } });
  const p = await c.newPage();
  await p.addLocatorHandler(p.locator('.modal.o_technical_modal').filter({ hasText: 'Open Customer Activities' }), (m) => m.locator('.btn-close').first().click({ timeout: 5000 }).catch(() => m.page().keyboard.press('Escape')));
  const o = new ServicePage(p);
  const cfg = d.equipmentConfig;
  const url = 'https://martiserv.averigoqa.com/odoo/case-management/17364'; await o.goto(url);
  console.log('CASE', url, await o.recordTitle());
  console.log('STATUSBAR', (await p.locator('.o_statusbar_status').innerText().catch(() => 'none')).replace(/\s+/g, ' '));
  console.log('BUTTONS', await p.evaluate(() => [...document.querySelectorAll('.o_form_view button')].filter((b) => b.offsetParent && b.innerText.trim()).map((b) => b.innerText.trim().replace(/\s+/g, ' ') + (b.name ? `{${b.name}}` : '')).join(' | ')));
  console.log('FIELDS', await p.evaluate(() => [...document.querySelectorAll('.o_form_view .o_field_widget[name]')].filter((e) => e.offsetParent).map((e) => e.getAttribute('name')).join(' ')));
  console.log('STAGE', await o.read('stage_id'));
  await o.click('close_case_btn'); await p.waitForTimeout(2000);
  const m = o.dialogs().last();
  console.log('DLG', (await m.innerText().catch(() => 'none')).replace(/\s+/g, ' ').slice(0, 400));
  console.log('DLG FIELDS', await m.evaluate((e) => [...e.querySelectorAll('.o_field_widget[name]')].filter((x) => x.offsetParent).map((x) => x.getAttribute('name') + ':' + (x.className.match(/o_field_(?!widget)\w+/g) || []).join(',') + (x.classList.contains('o_required_modifier') ? '*' : '')).join(' ')).catch(() => ''));
  console.log('DLG BUTTONS', await m.evaluate((e) => [...e.querySelectorAll('button')].filter((b) => b.offsetParent && b.innerText.trim()).map((b) => b.innerText.trim() + (b.name ? `{${b.name}}` : '')).join(' | ')).catch(() => ''));
  await b.close();
})();
