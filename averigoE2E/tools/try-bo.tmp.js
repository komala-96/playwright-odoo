const { chromium } = require('@playwright/test');
const env = require('../config/env');
const d = require('../data/testData');
const { SalesPage } = require('../pages/SalesPage');
(async () => {
  const b = await chromium.launch();
  const c = await b.newContext({ storageState: env.AUTH_FILE, baseURL: env.BASE_URL, viewport: { width: 1600, height: 1000 } });
  const p = await c.newPage();
  await p.addLocatorHandler(p.locator('.modal.o_technical_modal').filter({ hasText: 'Open Customer Activities' }), (m) => m.locator('.btn-close').first().click({ timeout: 5000 }).catch(() => m.page().keyboard.press('Escape')));
  const o = new SalesPage(p);
  const order = await o.createOrder({ customer: d.customer2.name, lines: [{ product: d.products.p2, qty: 100 }] });
  order.name = await o.confirmOrder(); console.log('ORDER', order.name);
  await o.openApp('Customer Care'); await o.openMenu('Delivery', 'Pick List');
  await o.rows(order.name).first().locator('td.o_list_record_selector').click();
  await p.locator('.o_control_panel button').filter({ hasText: /^\s*Packing Slip\s*$/ }).click();
  const slip = p.locator('.modal:visible').last();
  await slip.locator('.o_field_widget[name="select_all_pick"]').waitFor();
  console.log('PICK ROWS', await slip.locator('.o_field_widget[name="pick_list_ids"] .o_data_row').allInnerTexts());
  const row = slip.locator('.o_field_widget[name="pick_list_ids"] .o_data_row').filter({ hasText: d.products.p2.name }).first();
  await row.locator('td[name="sale_picking_qty"]').click();
  await row.locator('td[name="sale_picking_qty"] input').fill('50'); await row.locator('td[name="sale_picking_qty"] input').press('Tab'); await p.waitForTimeout(1000);
  console.log('MODALS AFTER QTY', (await p.locator('.modal:visible').allInnerTexts()).map((t) => t.slice(0, 200)));
  console.log('PICK ROWS 2', await slip.locator('.o_field_widget[name="pick_list_ids"] .o_data_row').allInnerTexts());
  await o.fill({ select_all_pick: true }, slip);
  await slip.locator('button[name="confirm_pack_slip"]').click(); await p.waitForTimeout(3000);
  console.log('MODALS AFTER CONFIRM', (await p.locator('.modal:visible').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ').slice(0, 300)));
  const bo = p.locator('.modal:visible').filter({ hasText: /create backorder/i }).last();
  console.log('BO FIELDS', await bo.evaluate((e) => [...e.querySelectorAll('.o_field_widget[name]')].map((x) => x.getAttribute('name') + ':' + x.className.match(/o_field_\w+/g)).join(' ')));
  await bo.locator('.o_data_row td[name]').last().click().catch(() => {}); await p.waitForTimeout(500);
  const rowCb = bo.locator('.o_data_row input[type=checkbox]').first();
  console.log('ROW CB before', await rowCb.isChecked());
  console.log('ROW CB after', await rowCb.isChecked());
  await bo.locator('button').filter({ hasText: /^\s*Continue\s*$/ }).click(); await o.waitReady(); await p.waitForTimeout(3000);
  console.log('MODALS AFTER CONTINUE', (await p.locator('.modal:visible').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ').slice(0, 300)));
  console.log('URL', p.url());
  console.log('STATUS', (await p.locator('.o_statusbar_status').allInnerTexts()).join(' / ').replace(/\s+/g, ' '));
  await p.screenshot({ path: 'tools/last.png' });
  await o.openApp('Customer Care'); await o.openMenu('Delivery', 'Backorders');
  console.log('BACKORDERS', (await o.rows().allInnerTexts()).slice(0, 3));
  console.log('BACKORDER for order?', await o.rows(order.name).count(), (await o.rows(order.name).allInnerTexts()).slice(0, 2));
  await o.openMenu('Delivery', 'Packing Slip');
  const h = p.locator('.o_list_view th[data-name="name"]'); await h.click(); await o.waitReady(); if (!(await h.getAttribute('class')).includes('o-sort-down')) { await h.click(); await o.waitReady(); }
  console.log('SLIPS', (await o.rows().allInnerTexts()).slice(0, 3));
  await o.goto(order.url);
  console.log('ORDER BUTTONS', await p.evaluate(() => [...document.querySelectorAll('.o_form_view button')].filter((b) => b.offsetParent && b.innerText.trim()).map((b) => b.innerText.trim().replace(/\s+/g, ' ')).join(' | ')));
  console.log('ORDER LINES', await o.field('order_line').locator('.o_data_row').allInnerTexts());
  require('fs').writeFileSync('tools/last-order-url.txt', order.url);
  await b.close();
})();
